# ===============================================
# 중학생 파이썬 예제: 성적표 엑셀 + 평균 그래프 만들기
# 필요한 프로그램 설치(명령 프롬프트에서 한 번만):
#   pip install pandas openpyxl matplotlib
# ===============================================

import pandas as pd                # 표(엑셀 같은 데이터)를 쉽게 다루는 도구를 불러와요
import matplotlib.pyplot as plt    # 그래프를 그리는 도구를 불러와요
import logging                     # 프로그램이 보여주는 안내 메시지를 조절하는 도구예요
logging.getLogger("matplotlib.font_manager").setLevel(logging.ERROR)   # "글꼴 없음" 같은 긴 경고 메시지는 숨겨요

# ----- 그래프에서 한글이 깨지지 않게 글꼴을 정해요 -----
# 컴퓨터마다 가진 글꼴이 달라서, 앞에서부터 있는 글꼴을 골라 써요
# (윈도우: 맑은 고딕, 맥: 애플고딕, 그 외: 나눔고딕 등)
plt.rcParams["font.family"] = ["Malgun Gothic", "AppleGothic", "NanumGothic", "WenQuanYi Zen Hei"]
plt.rcParams["axes.unicode_minus"] = False   # 그래프에서 마이너스(-) 기호가 깨지지 않게 해요

# ----- 1단계: 학생 10명의 이름과 점수를 리스트로 만들기 -----
이름 = ["김민준", "이서연", "박도윤", "최하은", "정시우",
        "강지아", "조예준", "윤수아", "장주원", "임채원"]   # 학생 이름 10개를 리스트에 담아요
국어 = [85, 92, 78, 95, 88, 73, 90, 82, 67, 99]          # 순서대로 각 학생의 국어 점수예요
영어 = [90, 88, 72, 91, 79, 85, 94, 76, 70, 96]          # 순서대로 각 학생의 영어 점수예요
수학 = [78, 95, 85, 89, 92, 68, 87, 90, 75, 94]          # 순서대로 각 학생의 수학 점수예요

# ----- 2단계: 학생별 평균 계산하기 -----
평균 = []                                   # 평균을 담을 빈 리스트를 만들어요
for i in range(len(이름)):                  # 학생 수(10명)만큼 반복해요. i는 0, 1, 2, ... 9가 돼요
    합계 = 국어[i] + 영어[i] + 수학[i]       # i번째 학생의 세 과목 점수를 더해요
    학생평균 = round(합계 / 3, 1)            # 3으로 나누고, 소수 첫째 자리까지 반올림해요
    평균.append(학생평균)                    # 계산한 평균을 평균 리스트 끝에 추가해요
    print(이름[i], "의 평균:", 학생평균)      # 화면에 학생 이름과 평균을 보여줘요

# ----- 3단계: 성적표.xlsx 엑셀 파일로 저장하기 -----
성적표 = pd.DataFrame({                      # 리스트들을 모아서 표를 만들어요
    "이름": 이름,                            # '이름' 칸에는 이름 리스트를 넣어요
    "국어": 국어,                            # '국어' 칸에는 국어 점수를 넣어요
    "영어": 영어,                            # '영어' 칸에는 영어 점수를 넣어요
    "수학": 수학,                            # '수학' 칸에는 수학 점수를 넣어요
    "평균": 평균,                            # '평균' 칸에는 방금 계산한 평균을 넣어요
})
성적표.to_excel("성적표.xlsx", index=False)   # 표를 엑셀 파일로 저장해요 (index=False: 왼쪽 번호 칸은 빼요)
print("성적표.xlsx 파일을 저장했어요!")        # 저장이 끝났다고 알려줘요

# ----- 4단계: 학생별 평균 막대그래프를 성적그래프.png로 저장하기 -----
plt.figure(figsize=(10, 6))                  # 가로 10, 세로 6 크기의 그림판을 준비해요
막대 = plt.bar(이름, 평균, color="skyblue")   # 이름을 가로축, 평균을 막대 높이로 하는 막대그래프를 그려요
plt.bar_label(막대)                          # 각 막대 위에 평균 숫자를 적어줘요
plt.title("학생별 평균 점수")                 # 그래프 맨 위에 제목을 붙여요
plt.xlabel("이름")                           # 가로축 이름을 붙여요
plt.ylabel("평균 점수")                       # 세로축 이름을 붙여요
plt.ylim(0, 100)                             # 세로축을 0점부터 100점까지로 정해요
plt.savefig("성적그래프.png", dpi=150)        # 그래프를 그림 파일로 저장해요 (dpi는 선명함 정도예요)
print("성적그래프.png 파일을 저장했어요!")      # 저장이 끝났다고 알려줘요
